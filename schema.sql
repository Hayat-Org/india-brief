create table if not exists articles (
  id               bigint generated by default as identity primary key,
  url              text unique not null,
  title            text not null,
  title_norm       text not null,
  snippet          text,
  source           text,
  source_kind      text default 'news',      -- govt | news | factcheck | state_gn
  feed_state       text,
  sources          jsonb default '[]'::jsonb, -- every outlet covering this story
  corroboration    int default 1,             -- number of distinct outlets
  published_at     timestamptz,
  category         text,
  state            text,
  significance     numeric(3,1),
  impact           numeric(3,1),
  interest         numeric(3,1),
  combined         numeric(3,1),
  sensitive        boolean default false,
  sensitive_reason text,
  is_factcheck     boolean default false,
  trend_boost      numeric(3,1) default 0,   -- bonus when the story matches a trending search in India
  status           text not null default 'new',
  -- new | candidate | discarded | pending_review | published | rejected | expired | failed
  hold_reason      text,
  draft            jsonb,
  card_url         text,
  breaking         boolean default false,
  results          jsonb,
  attempts         int default 0,
  created_at       timestamptz default now(),
  updated_at       timestamptz default now(),
  posted_at        timestamptz,
  review_sent_at   timestamptz
);

create index if not exists idx_articles_status on articles(status, combined desc);
create index if not exists idx_articles_created on articles(created_at desc);

create table if not exists settings (
  key        text primary key,
  value      text,
  updated_at timestamptz default now()
);

-- Only the service-role key (kept in GitHub Secrets) can read/write.
alter table articles enable row level security;
alter table settings enable row level security;

-- Public bucket for the generated post images (Instagram needs a public image URL).
insert into storage.buckets (id, name, public)
values ('cards', 'cards', true)
on conflict (id) do nothing;
